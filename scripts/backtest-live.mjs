// Re-price a props file's rows under the pool, as it would have stood that week.
function asPoolPriced(rows, model, slot) {
  const cand = rows.map((r) => {
    const proj = projectionProbOf(r);
    return {
      r,
      rotowirePlayerId: r.PlayerID,
      statKey: r.Stat,
      line: Number(r.Line),
      side: r.Side || "over",
      sportsbook: r.Book,
      odds: Number(r.Odds),
      oppositeOdds: r.OppositeOdds === "" || r.OppositeOdds === undefined ? null : Number(r.OppositeOdds),
      impliedProb: Number(r.ImpliedProb),
      fairProb: Number(r.FairProb),
      hold: r.Hold === "" || r.Hold === undefined ? null : Number(r.Hold),
      // The pool takes the projection's own probability as its input.
      ourProb: proj ?? Number(r.OurProb),
      projProb: proj ?? Number(r.OurProb),
      edge: Number(r.Edge),
      modelEdge: Number(r.ModelEdge),
    };
  });
  repriceWithPool(cand, model, { slot });
  return cand.map((c) => ({
    ...c.r,
    OurProb: c.ourProb.toFixed(4),
    ProjProb: c.projProb.toFixed(4),
    Edge: c.edge.toFixed(4),
    ModelEdge: c.modelEdge.toFixed(4),
    PriceModel: c.priceModel ?? c.r.PriceModel ?? "projection",
  }));
}

// Run the Firehose over the live boards re-priced under the other model, in a
// throwaway data directory so nothing in data/ is touched, and return its ledger.
function runCounterfactual(a, season, boards, model) {
  const tmp = mkdtempSync(join(tmpdir(), "backtest-live-"));
  try {
    for (const d of ["actuals", "closing", "projections", "players"]) {
      if (existsSync(join(ROOT, a.dataDir, d))) symlinkSync(join(ROOT, a.dataDir, d), join(tmp, d));
    }
    const used = [];
    for (const b of boards) {
      const rows = readCsv(b.path);
      const major = Object.entries(boardStats(rows).priceModels).sort((x, y) => y[1] - x[1])[0]?.[0] ?? "projection";
      const alt = counterfactualOf(major);
      const repriced = alt === "projection" ? rows.map(asProjectionPriced).filter(Boolean) : asPoolPriced(rows, model.at(b.week), b.slot);
      used.push({ week: b.week, slot: b.slot, asCaptured: major, counterfactual: alt });

      const dir = slotDir(b.slot);
      const edges = repriced.filter((r) => (r.Bettable === undefined || r.Bettable === "" || Number(r.Bettable) === 1) && Number(r.Edge) >= a.minEdge);
      for (const [kind, set] of [["props", repriced], ["edges", edges]]) {
        const d = join(tmp, kind, String(season), dir);
        mkdirSync(d, { recursive: true });
        writeFileSync(join(d, `week-${pad2(b.week)}.csv`), toCsv(PROPS_COLUMNS, set));
      }
    }
    const rel = relative(ROOT, tmp);
    const r = spawnSync(process.execPath, [join(__dirname, "simulate-personas.mjs"), "--data-dir", rel, "--persona", "firehose", "--season", String(season)], { encoding: "utf8" });
    if (r.status !== 0) throw new Error(`counterfactual replay failed: ${r.stderr || r.stdout}`);
    return { rows: loadLedger(rel, "firehose", season), used };
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

// ---------------------------------------------------------------------------

function main() {
  const a = parseArgs(process.argv.slice(2));
  const seasons = availableSeasons(join(ROOT, a.dataDir));
  const season = a.season ?? seasons[seasons.length - 1];
  if (!season) throw new Error(`No prop captures under ${a.dataDir}/props/`);

  const boards = liveBoards(a.dataDir, season, a.liveSlots);
  const live = (rows) => rows.filter((r) => isLiveSlot(r.Slot, a.liveSlots));
  const firehose = live(loadLedger(a.dataDir, "firehose", season));
  const latestWeek = Math.max(0, ...boards.map((b) => b.week), ...firehose.map((r) => Number(r.Week)));
  // A week is complete once a later week has been captured and its actuals exist.
  const completeWeeks = new Set(
    weekFiles(join(ROOT, a.dataDir, "actuals", String(season))).filter((w) => w < latestWeek)
  );

  // 1. Boards
  const boardRows = boards.map((b) => ({ ...b, stats: boardStats(readCsv(b.path), { minEdge: a.minEdge }) }));

  // 2. Pricing accuracy on live boards
  const { quotes, actualsByWeek } = loadSeason(season, { dataDir: join(ROOT, a.dataDir) });
  const model = buildSourceModel(quotes, actualsByWeek);
  const samples = liveSamples(quotes, actualsByWeek, model, a.liveSlots);
  const accWeeks = [...new Set(samples.map((s) => s.week))].sort((x, y) => x - y);
  const accuracy = { overall: pricingAccuracy(samples), byWeek: Object.fromEntries(accWeeks.map((w) => [w, pricingAccuracy(samples.filter((s) => s.week === w))])) };

  // 3. Bets
  const weekSlots = [...new Set(firehose.map((r) => `${r.Week}|${r.Slot || "main"}`))].sort((x, y) => Number(x.split("|")[0]) - Number(y.split("|")[0]) || x.localeCompare(y));
  const betsByWeek = weekSlots.map((k) => {
    const [w, slot] = k.split("|");
    const rows = firehose.filter((r) => String(r.Week) === w && (r.Slot || "main") === slot);
    const board = boardRows.find((b) => String(b.week) === w && b.slot === slot);
    return { week: Number(w), slot, models: [...new Set(rows.map((r) => r.PriceModel || "projection"))].join("+"), edgeRows: board?.stats.edges ?? null, summary: summarizeBets(rows, { completeWeeks }) };
  });
  const total = summarizeBets(firehose, { completeWeeks });
  const byModel = Object.fromEntries(
    [...new Set(firehose.map((r) => r.PriceModel || "projection"))].map((m) => [m, summarizeBets(firehose.filter((r) => (r.PriceModel || "projection") === m), { completeWeeks })])
  );

  // 3b. CLV by book. The closing prices are the live daily closing captures in
  // data/closing/, which is a different file from the backfilled closing board.
  const closingDir = join(ROOT, a.dataDir, "closing", String(season));
  const closingQuotes = weekFiles(closingDir).flatMap((w) =>
    readCsv(join(closingDir, `week-${pad2(w)}.csv`)).map((row) => readPropRow(row, "closing")).filter(Boolean)
  );
  const closingIndex = indexClosingConsensus(closingQuotes, { holdByStat: model.holdByStat });
  const byBook = summarizeByBook(firehose, { completeWeeks, closingIndex });

  // 4. Counterfactual
  let cf = null;
  if (a.counterfactual && boards.length > 0) {
    const { rows, used } = runCounterfactual(a, season, boards, model);
    const cfLive = live(rows);
    // Two different questions, kept apart: boards captured on the projection price
    // re-priced with the pool, and boards captured on the pool re-priced with the
    // projection. Summing them would mix a week-1 Tuesday drop with a Thursday one.
    const directions = {};
    for (const dir of ["pool", "projection"]) {
      const boardsD = used.filter((u) => u.counterfactual === dir);
      if (boardsD.length === 0) continue;
      const inD = (row) => boardsD.some((u) => u.week === Number(row.Week) && u.slot === (row.Slot || "main"));
      directions[dir] = {
        boards: boardsD.map((u) => `week ${u.week} ${u.slot}`),
        asCaptured: summarizeBets(firehose.filter(inD), { completeWeeks }),
        other: summarizeBets(cfLive.filter(inD), { completeWeeks }),
      };
    }
    cf = { used, directions };
  }

  // 5. Personas
  const personas = PERSONAS.map((p) => ({ id: p.id, label: p.label, summary: summarizeBets(live(loadLedger(a.dataDir, p.id, season)), { completeWeeks }) }));

  const result = { season, minEdge: a.minEdge, liveSlots: a.liveSlots, latestWeek, completeWeeks: [...completeWeeks], boards: boardRows, accuracy, betsByWeek, total, byModel, byBook, counterfactual: cf, personas };
  const markdown = render(result);

  if (a.json) console.log(JSON.stringify(result, null, 2));
  else console.log(markdown);

  if (a.write) {
    const dir = join(ROOT, a.dataDir, "backtest", String(season));
    mkdirSync(dir, { recursive: true });
    writeIfChanged(join(dir, "live.md"), markdown + "\n");
    writeIfChanged(join(dir, "live.json"), JSON.stringify(result, null, 2) + "\n");
    if (!a.json) console.log(`\nWrote ${join(a.dataDir, "backtest", String(season))}/live.md and live.json`);
  }
}

function writeIfChanged(path, text) {
  if (existsSync(path) && readFileSync(path, "utf8") === text) return;
  writeFileSync(path, text);
}

