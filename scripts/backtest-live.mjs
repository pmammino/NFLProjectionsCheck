function render(r) {
  const out = [];
  out.push(`# Live backtest — ${r.season}, through week ${r.latestWeek}`);
  out.push("");
  out.push(
    `Live means the ${r.liveSlots.join(", ")} captures: the prices and the projection that existed when the board was taken. ` +
      `Backfilled boards (opening, closing) are reconstructions with hindsight and are excluded. ` +
      `The Firehose takes every bettable edge of at least ${(100 * r.minEdge).toFixed(0)}% at one unit, at the best price per player and stat.`
  );

  out.push("", "## 1. Boards", "");
  if (r.boards.length === 0) out.push("No live captures yet.");
  else {
    out.push(
      table(
        ["week", "slot", "priced by", "rows", "markets", "books", "Pinnacle rows", "one-sided", "rows at the edge bar"],
        r.boards.map((b) => [
          b.week,
          b.slot,
          Object.keys(b.stats.priceModels).join("+"),
          b.stats.rows.toLocaleString(),
          b.stats.markets.toLocaleString(),
          b.stats.books,
          b.stats.pinnacleRows.toLocaleString(),
          pct(b.stats.oneSidedShare, 0).replace("+", ""),
          b.stats.edges,
        ])
      )
    );
    const odd = r.boards.filter((b) => Object.keys(b.stats.lineSources).some((s) => s !== "live"));
    if (odd.length) out.push("", `**Warning:** ${odd.map((b) => `${b.slot} week ${b.week}`).join(", ")} contain rows that are not live (${odd.map((b) => Object.keys(b.stats.lineSources).join("/")).join("; ")}). They are in the live ledger.`);
  }

  out.push("", "## 2. Pricing on live boards", "");
  const acc = r.accuracy.overall;
  if (acc.near.n === 0) out.push("No graded live markets with three or more books yet.");
  else {
    out.push("Brier score against what happened, markets within 0.25 of 50/50 by the book's price (lower is better). Gap = worse than the reference, clustered by player-week.", "");
    const row = (label, x) => [
      label,
      x.n.toLocaleString(),
      x.clusters,
      x.brierBook?.toFixed(4) ?? "–",
      x.brierProj?.toFixed(4) ?? "–",
      x.brierPool?.toFixed(4) ?? "–",
      x.projVsBook.n ? `${fx(x.projVsBook.mean)} (z ${x.projVsBook.z === null ? "–" : x.projVsBook.z.toFixed(1)})` : "–",
      x.poolVsBook.n ? `${fx(x.poolVsBook.mean)} (z ${x.poolVsBook.z === null ? "–" : x.poolVsBook.z.toFixed(1)})` : "–",
    ];
    out.push(
      table(
        ["", "markets", "player-weeks", "book", "projection", "pool", "projection − book", "pool − book"],
        [...Object.entries(r.accuracy.byWeek).map(([w, x]) => row(`week ${w}`, x.near)), row("**all weeks**", acc.near)]
      )
    );
    const thin = Object.entries(r.accuracy.byWeek).filter(([, x]) => x.near.clusters < 30).map(([w]) => w);
    if (thin.length) out.push("", `The z-scores use cluster-robust errors, which are unreliable under about 30 player-weeks (week${thin.length > 1 ? "s" : ""} ${thin.join(", ")}). Read the all-weeks row.`);
  }

  out.push("", "## 3. Bets: the Firehose, live only", "");
  if (r.betsByWeek.length === 0) out.push("No live bets yet.");
  else {
    out.push(
      table(
        ["week", "slot", "priced by", "rows at the edge bar", "bets", "settled", "pending", "ROI (±2σ)", "ROI if no-line overs lose", "CLV: beat the close"],
        [
          ...r.betsByWeek.map((b) => [b.week, b.slot, b.models, b.edgeRows ?? "–", b.summary.bets, b.summary.settled, pendingCell(b.summary), roiCell(b.summary), pct(b.summary.roiConservative), clvCell(b.summary)]),
          ["**all**", "", "", "", r.total.bets, r.total.settled, pendingCell(r.total), `**${roiCell(r.total)}**`, pct(r.total.roiConservative), clvCell(r.total)],
        ]
      )
    );
    out.push("", `Verdict on the live total: **${verdict(r.total)}**. "Rows at the edge bar" are the rows on the board that clear the minimum edge; the bets are what is left after the Firehose keeps one price per player and stat and the calibration guards (support floor, 20-point disagreement cap) are applied.`);
    if (Object.keys(r.byModel).length > 1) {
      out.push("", "By the price the board was captured under:", "");
      out.push(table(["price", "bets", "settled", "ROI (±2σ)", "CLV: beat the close"], Object.entries(r.byModel).map(([m, s]) => [m, s.bets, s.settled, roiCell(s), clvCell(s)])));
    }
  }

  out.push("", "## 3b. CLV by book", "");
  if (r.byBook.length === 0) out.push("No live bets yet.");
  else {
    out.push(
      "Where the bets came from and what their prices were worth. Each bet is taken at the best price across the books, so a book appears here when it was the best price. " +
        "**Own close** is the ledger's CLV: that book's closing price on the same line. **Market close** is the closing fair price of the *other* books on that line (at least two of them). " +
        "They can disagree: a slow book that never moves scores about zero against its own close even when its price was stale against everyone else. " +
        "† = fewer than " + MIN_CLV_FOR_A_BOOK + " measurable bets. ±2σ.",
      ""
    );
    const own = (s) => (s.clv.nMatched === 0 ? "–" : `${s.clv.nMatched} · ${(100 * s.clv.beatRate).toFixed(0)}% · ${s.clv.avgClvProb >= 0 ? "+" : ""}${(100 * s.clv.avgClvProb).toFixed(1)} pts${s.clv.nMatched < MIN_CLV_FOR_A_BOOK ? " †" : ""}`);
    const mkt = (m) => (!m || m.n === 0 ? "–" : `${m.n} · ${(100 * m.beatRate).toFixed(0)}% · ${m.avg >= 0 ? "+" : ""}${(100 * m.avg).toFixed(1)} ±${m.avgBand === null ? "?" : (100 * m.avgBand).toFixed(1)} pts${m.n < MIN_CLV_FOR_A_BOOK ? " †" : ""}`);
    out.push(
      table(
        ["book", "bets", "settled", "ROI (±2σ)", "own close: measurable · beat · avg", "market close: measurable · beat · avg"],
        r.byBook.map((b) => [b.label, b.summary.bets, b.summary.settled, roiCell(b.summary), own(b.summary), mkt(b.market)])
      )
    );
    const nBooks = r.byBook.length;
    const noMarket = r.byBook.reduce((a, b) => a + b.summary.bets - (b.market?.n ?? 0), 0);
    out.push("", `${nBooks} book${nBooks === 1 ? "" : "s"}. ${noMarket} of ${r.total.bets} bets have no market close: fewer than two other books quoted that exact line at the close, which is common for the one-sided alternate lines the slow books post.`);
  }

  out.push("", "## 4. The same live boards under the other price", "");
  if (!r.counterfactual) out.push("Not run.");
  else {
    const cf = r.counterfactual;
    out.push(
      "Each live board re-priced under the model it was *not* captured under and run through the same persona engine: boards captured on the projection price with the pool as it would have stood that week (weights fitted on earlier weeks), and boards captured on the pool with the projection price. The two directions are separate questions and are not added together.",
      ""
    );
    const rowsCf = [];
    for (const [dir, d] of Object.entries(cf.directions)) {
      const from = dir === "pool" ? "projection" : "pool";
      rowsCf.push([`${from}-priced boards (${d.boards.length}): as captured`, d.asCaptured.bets, d.asCaptured.settled, pendingCell(d.asCaptured), roiCell(d.asCaptured), clvCell(d.asCaptured)]);
      rowsCf.push([`… re-priced with the ${dir}`, d.other.bets, d.other.settled, pendingCell(d.other), roiCell(d.other), clvCell(d.other)]);
    }
    out.push(table(["", "bets", "settled", "pending", "ROI (±2σ)", "CLV: beat the close"], rowsCf));
    out.push("", "Boards: " + Object.entries(cf.directions).map(([dir, d]) => `${d.boards.join(", ")} (${dir === "pool" ? "projection" : "pool"} → ${dir})`).join("; ") + ".");
  }

  out.push("", "## 5. Every persona, live only", "");
  out.push(table(["persona", "bets", "settled", "pending", "ROI (±2σ)", "CLV: beat the close"], r.personas.map((p) => [p.label, p.summary.bets, p.summary.settled, pendingCell(p.summary), roiCell(p.summary), clvCell(p.summary)])));

  out.push("", "## 6. Can you read it?", "");
  const t = r.total;
  const need = t.roi !== null ? betsToResolve(t.roi, t.perBetSd) : null;
  const need5 = t.perBetSd ? betsToResolve(0.05, t.perBetSd) : null;
  const liveWeeks = new Set(r.betsByWeek.filter((b) => b.summary.settled > 0).map((b) => b.week)).size;
  const perWeek = liveWeeks > 0 ? t.settled / liveWeeks : null;
  const weeksFor = (n) => (perWeek ? Math.ceil((n - t.settled) / perWeek) : null);
  out.push(
    `- **Settled live bets: ${t.settled}.** A verdict needs at least ${MIN_BETS_FOR_A_VERDICT}, and the per-bet spread is ${t.perBetSd ? t.perBetSd.toFixed(2) : "–"} units.`,
    need !== null ? `- Seeing an ROI of ${pct(t.roi)} at two sigma takes about ${need.toLocaleString()} settled bets; you have ${t.settled}.` : "- No ROI to resolve yet.",
    need5 !== null
      ? `- Seeing a **5%** ROI takes about ${need5.toLocaleString()} settled bets. At the current ${perWeek ? perWeek.toFixed(0) : "–"} settled a week that is about ${weeksFor(need5) ?? "–"} more weeks — longer than a season.`
      : "",
    "- CLV resolves far faster than ROI because it is a price difference, not a coin flip, but it is partly mechanical: a slow book's off-market price stays off-market until the close.",
    "- Pending bets in finished weeks have no stat line. For an over that is almost always a loss the settlement cannot see; the conservative column counts them.",
    "- Bets on one player are correlated, so the bands are if anything too narrow."
  );
  return out.filter((l) => l !== "").length ? out.join("\n").replace(/\n{3,}/g, "\n\n") : "";
}

