function weekFiles(dir) {
  return existsSync(dir)
    ? readdirSync(dir)
        .map((f) => f.match(/^week-(\d+)\.csv$/))
        .filter(Boolean)
        .map((m) => Number(m[1]))
        .sort((x, y) => x - y)
    : [];
}

function loadLedger(dataDir, persona, season) {
  const dir = join(ROOT, dataDir, "bets", persona, String(season));
  return weekFiles(dir).flatMap((w) => readCsv(join(dir, `week-${pad2(w)}.csv`)));
}

// Every live capture's props file: { slot, week, path }.
function liveBoards(dataDir, season, liveSlots) {
  const base = join(ROOT, dataDir, "props", String(season));
  const out = [];
  for (const slot of liveSlots) {
    const dir = join(base, slotDir(slot));
    for (const week of weekFiles(dir)) out.push({ slot, week, path: join(dir, `week-${pad2(week)}.csv`) });
  }
  return out.sort((x, y) => x.week - y.week || x.slot.localeCompare(y.slot));
}

// ---------------------------------------------------------------------------
// Pricing accuracy on live boards
// ---------------------------------------------------------------------------

function liveSamples(quotes, actualsByWeek, model, liveSlots) {
  const groups = new Map();
  for (const q of quotes) {
    if (!isLiveSlot(q.slot, liveSlots) || !isPointInTime(q) || !isBettableStat(q.stat)) continue;
    const key = [q.slot, q.week, q.playerId, q.stat, q.line].join("|");
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(q);
  }
  const out = [];
  for (const rows of groups.values()) {
    const first = rows[0];
    const y = outcomeFrom(actualsByWeek, first);
    if (y === null) continue;
    const votes = bookVotes(rows, { assumedHold: model.holdByStat.get(first.stat) });
    if (votes.length < 3) continue;
    const m = model.at(first.week);
    const withProj = rows.find(isProjectionPrice);
    const pProj = withProj ? withProj.probOver : NaN;
    const pool = poolVotes(votes, {
      weights: weightsForStat(m, first.stat),
      projectionProb: Number.isFinite(pProj) ? pProj : null,
      projectionShare: shareFor(m.shares, first.stat, first.slot),
    });
    out.push({
      week: first.week,
      slot: first.slot,
      y,
      pBook: sigmoid(median(votes.map((v) => v.logit))),
      pProj,
      pPool: pool.prob,
      cluster: `${first.week}|${first.playerId}`,
    });
  }
  return out;
}

