const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const pad2 = (n) => String(n).padStart(2, "0");

function parseArgs(argv) {
  const a = { season: null, dataDir: "data", minEdge: 0.03, liveSlots: LIVE_SLOTS, counterfactual: true, write: false, json: false };
  for (let i = 0; i < argv.length; i++) {
    const next = () => argv[++i];
    switch (argv[i]) {
      case "--season": a.season = Number(next()); break;
      case "--data-dir": a.dataDir = next(); break;
      case "--min-edge": a.minEdge = Number(next()); break;
      case "--live-slots": a.liveSlots = next().split(",").map((s) => s.trim()).filter(Boolean); break;
      case "--no-counterfactual": a.counterfactual = false; break;
      case "--write": a.write = true; break;
      case "--json": a.json = true; break;
      case "-h":
      case "--help":
        console.log("Usage: node scripts/backtest-live.mjs [--season Y] [--min-edge 0.03] [--live-slots a,b] [--no-counterfactual] [--write] [--json]");
        process.exit(0);
        break;
      default:
        throw new Error(`Unknown argument: ${argv[i]}`);
    }
  }
  if (!(a.minEdge >= 0)) throw new Error("--min-edge must be >= 0");
  return a;
}

// ---------------------------------------------------------------------------
// Formatting
// ---------------------------------------------------------------------------

const pct = (x, d = 1) => (x === null || x === undefined || !Number.isFinite(x) ? "–" : `${x >= 0 ? "+" : ""}${(100 * x).toFixed(d)}%`);
const fx = (x, d = 4) => (x === null || x === undefined || !Number.isFinite(x) ? "–" : `${x >= 0 ? "+" : ""}${x.toFixed(d)}`);
const roiCell = (s) => (s.settled === 0 ? "–" : `${pct(s.roi)} ±${s.roiBand === null ? "?" : (100 * s.roiBand).toFixed(0)}%`);
const clvCell = (s) =>
  s.clv.nMatched === 0 ? "–" : `${(100 * s.clv.beatRate).toFixed(0)}% of ${s.clv.nMatched}, ${s.clv.avgClvProb >= 0 ? "+" : ""}${(100 * s.clv.avgClvProb).toFixed(1)} pts`;
const pendingCell = (s) => `${s.unplayed}${s.noLine ? ` + ${s.noLine} no line` : ""}${s.noSource ? ` + ${s.noSource} ungradable` : ""}`;

function table(headers, rows) {
  const line = (cells) => `| ${cells.join(" | ")} |`;
  return [line(headers), line(headers.map(() => "---")), ...rows.map(line)].join("\n");
}

