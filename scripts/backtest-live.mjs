// The weekly live-only backtest: what the paper ledger earned on the boards we
// actually had at the time, how the two prices compare on those same boards, and
// how much of any of it is more than noise.
//
// Live means the Tuesday, Thursday and Saturday captures. A backfilled board
// (opening, closing) is a reconstruction with hindsight in it and is excluded by
// slot; see lib/backtest-live.mjs for why, and for why most of what remains is
// still noise.
//
// Sections:
//   1. BOARDS        what each live capture contained, and under which price
//   2. PRICING       Brier of the book, the projection and the pool on live boards
//   3. BETS          the Firehose (every edge >= the minimum, 1u, best price), by
//                    week and slot, with the ROI band and CLV
//   4. COUNTERFACTUAL the same live boards re-priced under the OTHER model and
//                    run through the same persona engine
//   5. PERSONAS      every persona, live only
//   6. CAN YOU READ IT? how many bets it takes to see an effect of that size
//
// Usage:
//   npm run backtest-live
//   node scripts/backtest-live.mjs [--season 2026] [--min-edge 0.03]
//                                  [--live-slots main,thursday,saturday]
//                                  [--no-counterfactual]
//                                  [--write]   data/backtest/{season}/live.md + .json
//                                  [--json]
//
// Reads the ledgers in data/bets/ (regenerated by simulate-personas.mjs, so run
// that first if the actuals are new) and the captures in data/props/.

